// Linux aarch64 (`asm-generic`) syscall numbers.
//
// arm64 uses the asm-generic ABI, a *different* numbering than x86_64
// and a different set: no legacy `open`/`stat`/`poll`/`select`/`fork`,
// only their `*at`/`ppoll`/`pselect6`/`clone` forms. The numbers here
// are the values musl/glibc emit when an aarch64 binary calls
// `syscall(N, ...)`; taken from the resolved arm64 ABI table.
//
// A name with no arm64 number is given a distinct sentinel far above any
// real one. The dispatch arm that names it is present but can never be
// matched, because no aarch64 libc emits that legacy call - the same
// handler is reached through the modern form's own number. The sentinel
// is a compile convenience, not an addressable syscall.

